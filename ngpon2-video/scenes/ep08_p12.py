        self.at(self.q("her patlamaya göre yeniden ayarlamalıdır", 25))
        self.play(Indicate(warn, color=WARN), run_time=0.6)
        self.end(pad=0.1)
        self.clear()
        self.save_timeline("ep08_p1A")



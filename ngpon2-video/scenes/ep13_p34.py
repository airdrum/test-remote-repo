def xor_c(r=0.2, color=GOLD, sw=2.5):
    c = Circle(radius=r, color=color, stroke_width=sw)
    return VGroup(c, Line(c.get_left(), c.get_right(), color=color, stroke_width=sw), Line(c.get_top(), c.get_bottom(), color=color, stroke_width=sw))


def blocks(n=5, wpb=4, cw=0.5, h=0.5, names=None, y=0.0, x0=None):
    """n 16-byte blocks of `wpb` 4-byte words. Returns (VGroup(word rects), VGroup(block outlines), VGroup(labels))."""
    W = VGroup(*[Rectangle(width=cw, height=h, stroke_color=LINE, stroke_width=1.2, fill_color=PANEL, fill_opacity=1) for _ in range(n * wpb)]).arrange(RIGHT, buff=0)
    if x0 is None:
        W.move_to([0, y, 0])
    else:
        W.move_to([x0, y, 0], aligned_edge=LEFT)
    B = VGroup(*[Rectangle(width=cw * wpb, height=h, stroke_color=MUTED, stroke_width=2.5).move_to(W[k * wpb:(k + 1) * wpb]) for k in range(n)])
    L = VGroup(*[T(nm, 15, MUTED, BOLD).next_to(B[k], DOWN, buff=0.08) for k, nm in enumerate(names or [])])
    return W, B, L


def paint(ws, color, op=0.5, lab=None, size=14):
    g = VGroup(*[w.copy().set_fill(color, opacity=op).set_stroke(color, width=1.5) for w in ws])
    if lab:
        g.add(T(lab, size, BG if op >= 0.5 else TXT, BOLD).move_to(g))
    return g



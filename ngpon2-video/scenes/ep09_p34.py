        tc = self.title_card("PERDE 3", "AMCC")
        self.at(self.cue("B eki standardın", 3.9))
        self.to_header(tc)
        self.set_badge("std")
        h = self.show_heading("Ek B: yardımcı yönetim ve denetim kanalı")
        rows = []
        for k, y in enumerate((1.15, 0.0, -1.15)):
            o = sbox(f"OLT CT {k + 1}", None, OLTC, 1.6, 0.55, 16).move_to([-5.5, y, 0])

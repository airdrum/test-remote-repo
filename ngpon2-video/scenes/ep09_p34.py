        mp = VGroup(Line([LX(1.03125e10), 0.55, 0], [LX(1.03125e10), 1.35, 0], color=PTP, stroke_width=5), T("yük 10,3125 Gbit/s", 18, PTP, BOLD).move_to([LX(1.03125e10) - 0.3, 1.6, 0]))

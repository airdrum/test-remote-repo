        self.play(FadeIn(ma, shift=DOWN * 0.1), run_time=0.4)
        self.at(self.cue("doksan binde", 7.3))
        self.play(GrowFromCenter(rr), FadeIn(rt), run_time=0.6)
        self.at(self.cue("Ama bu fısıltı", 11.0))
        self.play(FadeIn(tt, shift=UP * 0.1), self.set_src("G.989.2 Ek B"), run_time=0.5)
        self.at(self.cue("bir güç cezası vermez", 18.8))

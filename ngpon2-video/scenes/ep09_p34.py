        ba = BraceBetweenPoints([1.45, -2.03, 0], [1.45, -1.87, 0], RIGHT, color=AMC)
        bat = T("Vpp,AMCC (%10)", 15, AMC, BOLD).next_to(aw, UP, buff=0.18)
        fm = T("M = 100 · Vpp,AMCC / Vpp,yük", 22, TXT, BOLD).move_to([4.5, -1.95, 0])
        self.play(FadeIn(pay), FadeIn(drv), FadeIn(las), Create(fib), GrowArrow(a3), GrowArrow(a4), FadeIn(sig), GrowArrow(a1), self.set_src("G.989.2 Ek B · B.2.2 · Tablo B.2"), run_time=0.8)
        self.at(self.cue("düşük taşıyıcı frekanslı", 2.2))
        self.play(FadeIn(amc, shift=RIGHT * 0.1), GrowArrow(a2), run_time=0.6)
        self.at(self.cue("elektriksel alanda", 8.8))
        self.play(Create(el), FadeIn(elt), Indicate(sig, color=GOLD), run_time=0.8)
        self.at(self.cue("Tablo B iki'nin", 11.7))
        self.play(FadeIn(tb[0]), run_time=0.4)
        for k, (key, d) in enumerate((("saniyede yüz yirmi", 13.9), ("yüzde on modülasyon", 16.7), ("beş yüz kilohertz", 19.0))):
            self.at(self.cue(key, d))
            self.play(FadeIn(tb[k + 1], shift=UP * 0.05), run_time=0.45)

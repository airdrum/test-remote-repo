def comp_tile(name, sub, color, w=1.15, h=0.62, size=26):
    r = RoundedRectangle(corner_radius=0.1, width=w, height=h, stroke_color=color, stroke_width=2.2, fill_color=color, fill_opacity=0.14)
    s = sym(name, sub, color, size).move_to(r)
    return VGroup(r, s)


def descriptor_row(ext=False, size=26):
    """⟨RF, RA, RM, χAB, P, ω[, TJT, TBDT, TPST]⟩ as coloured tiles. Returns (row, tiles)."""
    spec = [("R", "F", FXC), ("R", "A", ASC), ("R", "M", RMC), ("χ", "AB", NAC), ("P", "", MUTED), ("ω", "", MUTED)]
    if ext:
        spec += [("T", "JT", TJC), ("T", "BDT", TBC), ("T", "PST", TPC)]
    tl = VGroup(*[comp_tile(a, b, c, 1.15 if len(b) < 3 else 1.35, 0.62, size) for a, b, c in spec]).arrange(RIGHT, buff=0.12)
    row = VGroup(T("D = ⟨", size + 4, TXT, BOLD), tl, T("⟩", size + 4, TXT, BOLD)).arrange(RIGHT, buff=0.15)
    return row, tl



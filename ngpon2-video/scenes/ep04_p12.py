def clock_icon(r=0.35, color=GOLD):
    c = Circle(radius=r, color=color, stroke_width=3)
    hands = VGroup(Line(ORIGIN, UP * r * 0.62, color=color, stroke_width=3), Line(ORIGIN, RIGHT * r * 0.45, color=color, stroke_width=3))
    ticks = VGroup(*[Line(r * 0.78 * np.array([np.cos(a), np.sin(a), 0]), r * 0.95 * np.array([np.cos(a), np.sin(a), 0]), color=color, stroke_width=2)
                     for a in np.arange(0, 2 * np.pi, np.pi / 2)])
    return VGroup(c, hands, ticks)


def miller_psd(fT):
    w = 2 * np.pi * fT
    num = 23 - 2 * np.cos(w / 2) - 22 * np.cos(w) - 12 * np.cos(1.5 * w) + 5 * np.cos(2 * w) + 12 * np.cos(2.5 * w) + 2 * np.cos(3 * w) - 8 * np.cos(3.5 * w) + 2 * np.cos(4 * w)
    return 2 / (w ** 2 * (17 + 8 * np.cos(4 * w))) * num



def tcard(k, title, body, w=6.5, h=0.95, tsize=19, bsize=16):
    """Threat card: coloured number, title, one body line."""
    c = THC[k]
    r = RoundedRectangle(corner_radius=0.12, width=w, height=h, stroke_color=c, stroke_width=2.2, fill_color=PANEL, fill_opacity=1)
    n = T(str(k + 1), 34, c, BOLD).move_to(r).align_to(r, LEFT).shift(RIGHT * 0.3)
    g = VGroup(T(title, tsize, c, BOLD), T(body, bsize, TXT, SEMIBOLD)).arrange(DOWN, aligned_edge=LEFT, buff=0.08)
    fit(g, w - 1.0).next_to(n, RIGHT, buff=0.3)
    return VGroup(r, n, g)


def eqrow(out, key, msg, y, x_out=-5.9, x_eq=-3.85, x_key=-1.7, x_msg=-0.45):
    """'OUT = AES-CMAC( KEY , MSG )' row; returns VGroup(out, eq, key, comma, msg, close)."""
    out.move_to([x_out, y, 0])
    eq = T("= AES-CMAC (", 19, MICC, BOLD).move_to([x_eq, y, 0])
    key.move_to([x_key, y, 0])
    cm = T(",", 20, MUTED, BOLD).next_to(key, RIGHT, buff=0.08).align_to(key, DOWN)
    msg.move_to([x_msg, y, 0], aligned_edge=LEFT)
    cl = T(")", 20, MICC, BOLD).next_to(msg, RIGHT, buff=0.1)
    return VGroup(out, eq, key, cm, msg, cl)



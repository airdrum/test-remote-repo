def ctr_col(x, k, y_ctr=1.55, y_aes=0.6, y_x=-0.35):
    """One CTR column: counter tile → AES box → ⊕ with P_k → C_k. Returns dict."""
    ctr = tile("ICB" if k == 0 else f"ICB + {k}", SFCC8, 1.55, 0.46, 16, 0.18).move_to([x, y_ctr, 0])
    aes = tile("AES-128 · K", ACC, 1.75, 0.5, 16, 0.25).move_to([x, y_aes, 0])
    xo = VGroup(Circle(radius=0.2, stroke_color=TXT, stroke_width=2.2), T("+", 22, TXT, BOLD)).move_to([x, y_x, 0])
    p = tile(f"P{k + 1}", GOOD, 0.7, 0.42, 16, 0.15).next_to(xo, LEFT, buff=0.4)
    c = tile(f"C{k + 1}", PINK, 0.7, 0.42, 16, 0.3).next_to(xo, DOWN, buff=0.35)
    a1 = arrow(ctr.get_bottom(), aes.get_top(), MUTED, 2, 0.1)
    a2 = arrow(aes.get_bottom(), xo.get_top(), ACC, 2, 0.1)
    a3 = arrow(p.get_right(), xo.get_left(), GOOD, 2, 0.1)
    a4 = arrow(xo.get_bottom(), c.get_top(), PINK, 2, 0.1)
    return {"ctr": ctr, "aes": aes, "xo": xo, "p": p, "c": c, "a": VGroup(a1, a2, a3, a4)}


def hexcells(bs, color=TXT, size=17, w=0.62, h=0.46, op=0.08, stroke=None):
    return VGroup(*[hexbox(b, color, size, stroke=stroke, w=w, h=h, op=op) for b in bs.split()]).arrange(RIGHT, buff=0.06)



def wave(bits, x0, x1, y, h, color, sw=2.5):
    tb = (x1 - x0) / len(bits)
    return VMobject(stroke_color=color, stroke_width=sw).set_points_as_corners(
        nrz(bits, x0, tb, y - h / 2, y + h / 2, rise=min(0.04, tb * 0.3)))



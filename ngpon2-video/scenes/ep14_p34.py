def burst(x0, y, ovh, pay, h=0.4, pc=SAC, pop=0.35, ov_lab=None, p_lab=None, size=14):
    """One upstream burst: per-burst overhead (Tplo) followed by its payload."""
    return strip([(ovh, ov_lab or "", OVC, 0.45), (pay, p_lab or "", pc, pop)], x0, y, h, size)



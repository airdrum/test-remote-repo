def fam_card(title, body, chip, color, w=4.05, h=1.5):
    r = RoundedRectangle(corner_radius=0.14, width=w, height=h, stroke_color=color, stroke_width=2.2, fill_color=PANEL, fill_opacity=1)
    t = T(title, 18, color, BOLD).move_to(r.get_corner(UL) + [0.2, -0.27, 0], aligned_edge=LEFT)
    b = fit(T(body, 15, TXT, SEMIBOLD, line_spacing=0.9), w - 0.4).next_to(t, DOWN, buff=0.14).align_to(t, LEFT)
    g = VGroup(r, t, b)
    if chip:
        c = tag(chip, MUTED, 14).move_to(r.get_corner(UR) + [-0.2, -0.27, 0], aligned_edge=RIGHT)
        g.add(c)
    return g



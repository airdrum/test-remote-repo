def nterm(s, name, color=TXT, size=22, nsize=14):
    return term(s, name, color, size, nsize)


def eq_row(label, parts, lcolor=TXT, size=22, nsize=14, buff=0.18):
    """label + [(text, name, color) | operator string] → aligned row of named terms (tops aligned)."""
    g = VGroup(T(label, size, lcolor, BOLD))
    ops = []
    for p in parts:
        if isinstance(p, str):
            ops.append(T(p, size, TXT, BOLD))
            g.add(ops[-1])
        else:
            g.add(nterm(p[0], p[1], p[2], size, nsize))
    g.arrange(RIGHT, buff=buff, aligned_edge=UP)
    yref = next(m for m in g[1:] if m not in ops)[0].get_y()
    for m in [g[0]] + ops:
        m.set_y(yref)
    return g


